/**
 * Verified Camera Models array - points directly to the centralized database
 * for 100% backward compatibility across the entire application
 */
export const VERIFIED_CAMERA_MODELS: CameraSpecs[] = CAMERA_SPECIFICATIONS;

/**
 * Look up a camera specification by its unique ID or exact model name
 */
export function getCameraSpecification(idOrModelName: string): CameraSpecification | undefined {
  if (!idOrModelName) return undefined;
  const target = idOrModelName.toLowerCase().trim();
  return CAMERA_SPECIFICATIONS.find(
    (spec) =>
      spec.id.toLowerCase() === target ||
      spec.model.toLowerCase() === target ||
      spec.modelName.toLowerCase() === target ||
      spec.modelName.toLowerCase().includes(target)
  );
}

/**
 * Look up camera specifications by manufacturer
 */
export function getCameraSpecificationsByManufacturer(mfr: string): CameraSpecification[] {
  if (!mfr || mfr.toLowerCase() === 'all') return [...CAMERA_SPECIFICATIONS];
  return CAMERA_SPECIFICATIONS.filter((s) => s.manufacturer.toLowerCase() === mfr.toLowerCase());
}

/**
 * Get all available camera specifications
 */
export function getAllCameraSpecifications(): CameraSpecification[] {
  return [...CAMERA_SPECIFICATIONS];
}

